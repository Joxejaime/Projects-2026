#!/usr/bin/env python3
"""Generate SLO recording and burn-rate alert rules (Google SRE Workbook, ch. 5).

Edit the SLO definitions below, run `python3 gen_slo_rules.py`, commit the output.
`python3 gen_slo_rules.py --check` exits non-zero if the committed files are stale,
so CI catches hand-edits that drift from the single source of truth.
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).parent / "rules"
SERVICE = "release-tracker"
SELECTOR = f'job="{SERVICE}",route=~"/api/.*"'  # health, readiness and metrics are not user traffic
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]

SLOS = {
    "availability": {
        "target": 0.995,
        "description": "99.5% of /api requests succeed (non-5xx), measured over 30 days",
        # error ratio = 5xx / all; `or vector(0)` keeps the ratio at 0 (not absent) before the first 5xx series exists
        "ratio": lambda w: (
            f'(sum(rate(http_requests_total{{{SELECTOR},status=~"5.."}}[{w}])) or vector(0))\n'
            f"/\nsum(rate(http_requests_total{{{SELECTOR}}}[{w}]))"
        ),
        "alerts": [
            # (name, burn rate, long window, short window, for, severity)
            ("AvailabilityFastBurn", 14.4, "1h", "5m", "2m", "page"),
            ("AvailabilityMediumBurn", 6, "6h", "30m", "15m", "page"),
            ("AvailabilitySlowBurn", 3, "1d", "2h", "1h", "ticket"),
            ("AvailabilityBudgetLeak", 1, "3d", "6h", "3h", "ticket"),
        ],
    },
    "latency": {
        "target": 0.95,
        "description": "95% of /api requests complete in under 250 ms, measured over 30 days",
        # slow ratio = 1 - (requests <= 250ms / all)
        "ratio": lambda w: (
            f'1 - (\nsum(rate(http_request_duration_seconds_bucket{{{SELECTOR},le="0.25"}}[{w}]))\n'
            f'/\nsum(rate(http_request_duration_seconds_bucket{{{SELECTOR},le="+Inf"}}[{w}]))\n)'
        ),
        "alerts": [
            ("LatencyFastBurn", 6, "1h", "5m", "5m", "page"),
            ("LatencySlowBurn", 1, "6h", "30m", "30m", "ticket"),
        ],
    },
}


def indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line for line in text.splitlines())


def recording() -> str:
    lines = [
        "# GENERATED by prometheus/gen_slo_rules.py: do not edit by hand.",
        "groups:",
        "  - name: slo-recording",
        "    interval: 30s",
        "    rules:",
    ]
    for slo, cfg in SLOS.items():
        budget = round(1 - cfg["target"], 6)
        lines += [
            f"      - record: slo:{slo}_error_budget:ratio",
            f"        expr: vector({budget})",
            "        labels:",
            f"          service: {SERVICE}",
        ]
        for w in WINDOWS:
            lines += [
                f"      - record: slo:{slo}_error_ratio:rate{w}",
                "        expr: |",
                indent(cfg["ratio"](w), 10),
                "        labels:",
                f"          service: {SERVICE}",
            ]
    return "\n".join(lines) + "\n"


def alerts() -> str:
    lines = [
        "# GENERATED by prometheus/gen_slo_rules.py: do not edit by hand.",
        "groups:",
        "  - name: slo-burn-rate-alerts",
        "    rules:",
    ]
    for slo, cfg in SLOS.items():
        budget = 1 - cfg["target"]
        for name, burn, long_w, short_w, hold, severity in cfg["alerts"]:
            threshold = round(burn * budget, 6)
            lines += [
                f"      - alert: {name}",
                "        expr: |",
                f"          slo:{slo}_error_ratio:rate{long_w}{{service=\"{SERVICE}\"}} > {threshold}",
                "          and",
                f"          slo:{slo}_error_ratio:rate{short_w}{{service=\"{SERVICE}\"}} > {threshold}",
                f"        for: {hold}",
                "        labels:",
                f"          severity: {severity}",
                f"          service: {SERVICE}",
                f"          slo: {slo}",
                "        annotations:",
                f'          summary: "{SERVICE} {slo} SLO: burning error budget at {burn}x"',
                "          description: >-",
                f"            {cfg['description']}. Over both {long_w} and {short_w} the bad-request ratio",
                f"            exceeds {threshold} ({burn}x the sustainable burn rate); at this pace the",
                "            30-day error budget is exhausted early.",
                f"          runbook: docs/runbooks/{slo}-burn.md",
            ]
    return "\n".join(lines) + "\n"


def main() -> int:
    files = {"slo-recording.yml": recording(), "slo-alerts.yml": alerts()}
    if "--check" in sys.argv:
        stale = [n for n, body in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != body]
        if stale:
            print(f"STALE generated rules: {', '.join(stale)}; run gen_slo_rules.py")
            return 1
        print("OK: generated SLO rules are up to date")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, body in files.items():
        (OUT / name).write_text(body)
        print(f"wrote {OUT / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
